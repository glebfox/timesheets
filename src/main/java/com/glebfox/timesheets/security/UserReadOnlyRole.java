package com.glebfox.timesheets.security;

import com.glebfox.timesheets.entity.user.User;
import io.jmix.security.model.EntityAttributePolicyAction;
import io.jmix.security.model.EntityPolicyAction;
import io.jmix.security.role.annotation.EntityAttributePolicy;
import io.jmix.security.role.annotation.EntityPolicy;
import io.jmix.security.role.annotation.ResourceRole;
import io.jmix.securityflowui.role.annotation.MenuPolicy;
import io.jmix.securityflowui.role.annotation.ViewPolicy;

/**
 * Reading users: the user list and the user editor, with every attribute view-only. For any role that needs to show or
 * pick users.
 */
@ResourceRole(name = "User: read only", code = UserReadOnlyRole.CODE)
public interface UserReadOnlyRole {

    String CODE = "user-read-only";

    @EntityAttributePolicy(entityClass = User.class, attributes = "*", action = EntityAttributePolicyAction.VIEW)
    @EntityPolicy(entityClass = User.class, actions = EntityPolicyAction.READ)
    void user();

    @ViewPolicy(viewIds = {"ts_User.list", "ts_User.detail"})
    @MenuPolicy(menuIds = "ts_User.list")
    void userScreens();
}
